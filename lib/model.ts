// Token Radar model (radar-2): one sealed snapshot in, one ranked board out.
//
// Who is ranked. A protocol is "genuine" (a candidate for a real launch) when it
// records no token at all (mcap_usd, gecko_id and symbol all null) AND its category
// is not Bridge / Canonical Bridge / Liquid Staking / Liquid Restaking / Restaked
// BTC / CEX, AND its name does not end in a version marker, carries no whole word
// wrapped / staked / staking, and does not start with an exchange name. That is the
// watchlist rule applied to the whole snapshot, not just the $50M floor: 198
// protocols here, the 40 watchlist slugs plus 158 below the floor. Live-token
// protocols are never ranked; they are set aside with their market caps.
//
// Implied value, from the snapshot's own figures only (no name is special-cased):
//
//   multiple(cat) = median(mcap_usd / tvl_usd) over LIVE protocols of that category
//                   in this snapshot (needs >= 3 live; else FALLBACK_MULTIPLE)
//   base          = tvl_usd * multiple(cat)
//   growth        = clamp(change_7d, -50, 100); growthMult = 1 + (growth/100) * 0.5
//   age           = days from listed_at to as_of (null -> 365)
//   maturityMult  = 0.6 + min(age, 1095) / 1095 * 0.4
//   chainMult     = 1 + min(max(chains.length - 1, 0), 4) * 0.02
//   implied       = max(1, round(base * growthMult * maturityMult * chainMult))
//
// Rank is implied descending, ties broken by slug ascending. Deterministic: no
// clock, no randomness, no network.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_extra: number;
  fallback_multiple: number;
  min_live_for_multiple: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  chain_step: 0.02,
  chain_max_extra: 4,
  fallback_multiple: 0.205,
  min_live_for_multiple: 3,
};

